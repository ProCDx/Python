# Arithmetic Operators
print(1 + 1)    # 2  addition
print(2 - 1)    # 1  subtraction
print(2 * 2)    # 4  multiplication
print(4 / 2)    # 2.0 division (always float)
print(4 % 3)    # 1  remainder
print(4 ** 2)   # 16 exponent
print(5 // 2)   # 2  floor division

print(-4)       # unary minus
print("Roger" + " is a good dog")   # + also concatenates strings

# Compound assignment
age = 8
age += 1        # same as age = age + 1
age *= 2
print(age)      # 18
