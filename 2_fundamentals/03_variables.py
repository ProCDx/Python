# Variables
# A variable is a name that refers to a value. Created by assigning with =.

name = "projay"
age = 21
print(name, age)

# Rules: letters, numbers and _ only; cannot start with a number;
# cannot be a keyword (for, if, while, import...). Names are case sensitive.
name1 = "ok"
AGE = 10        # different from age
_private = True

# Python is dynamically typed - a variable can be reassigned to any type.
age = "eight"
print(age)
