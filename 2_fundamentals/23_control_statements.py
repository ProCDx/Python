# Control Statements: if / elif / else
condition = True

if condition == True:
    print("The condition")
    print("was true")
else:
    print("The condition was false")

name = "Roger"
if name == "Roger":
    print("Hello Roger")
elif name == "Syd":
    print("Hello Syd")
elif name == "Flavio":
    print("Hello Flavio")
else:
    print("Hello stranger")
